"""Build the editable watch UI assets. Requires Pillow and numpy.

The C font bitmaps, not a browser substitute, are consumed by the LVGL preview
and firmware. Photographs are used only for comparison, never as a face image.
"""
from pathlib import Path
import json
import math
import shutil
import numpy as np
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
OUT = ROOT / 'output/watchface'
ASSETS = ROOT / 'components/watch_shell/assets'
LAYOUT = json.loads((HERE / 'layout.json').read_text(encoding='utf-8'))
S = 4


def chunks(data, n=24):
    return '\n'.join('    ' + ','.join(f'0x{x:02x}' for x in data[i:i+n]) + ','
                     for i in range(0, len(data), n))


def image_c(image, name, alpha=False):
    image.save(OUT / f'{name}.png')
    a = np.asarray(image.convert('RGBA' if alpha else 'RGB'), dtype=np.uint8)
    if alpha:
        data = a[:, :, [2, 1, 0, 3]].tobytes()
        fmt, stride = 'ARGB8888', image.width * 4
    else:
        v = ((a[:, :, 0].astype(np.uint16) >> 3) << 11) | \
            ((a[:, :, 1].astype(np.uint16) >> 2) << 5) | (a[:, :, 2] >> 3)
        data = v.astype('<u2').tobytes()
        fmt, stride = 'RGB565', image.width * 2
    text = f'''/* Generated by tools/watchface/generate.py; uncompressed for XIP. */
#include "lvgl.h"
static const uint8_t {name}_data[] = {{
{chunks(data)}
}};
const lv_image_dsc_t {name} = {{
    .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_{fmt},
                 .flags = 0, .w = {image.width}, .h = {image.height}, .stride = {stride} }},
    .data_size = sizeof({name}_data), .data = {name}_data,
}};
'''
    (ASSETS / f'{name}.c').write_text(text, encoding='utf-8')


def font_c(path, name, size, symbols, xscale=1.0, round_colon=False):
    primary = ImageFont.truetype(str(path), size)
    fallback = ImageFont.truetype(str(HERE/'fonts/ChillRoundF.ttf'), size)
    missing = bytes(primary.getmask(chr(0x10ffff)))
    glyphs = []
    for c in sorted(set(symbols), key=ord):
        font = fallback if bytes(primary.getmask(c)) == missing else primary
        x0, y0, x1, y1 = font.getbbox(c, anchor='ls')
        mask = Image.new('L', (max(1,x1-x0), max(1,y1-y0)))
        ImageDraw.Draw(mask).text((-x0,-y0), c, font=font, anchor='ls', fill=255)
        advance = font.getlength(c)
        if round_colon and c == ':':
            y0, y1, x0 = -57, -12, 3
            mask = Image.new('L', (40,180))
            d = ImageDraw.Draw(mask)
            d.ellipse((0,0,39,39), fill=255)
            d.ellipse((0,140,39,179), fill=255)
            mask = mask.resize((10,45), Image.Resampling.LANCZOS)
            advance = 17
        if xscale != 1:
            mask = mask.resize((max(1,round(mask.width*xscale)),mask.height),Image.Resampling.LANCZOS)
            x0 = round(x0*xscale)
        advance = round(advance*xscale*16)
        glyphs.append((c,mask,x0,y0,y1,advance))
    top = min(g[3] for g in glyphs)
    bottom = max(g[4] for g in glyphs)
    bitmap = bytearray()
    desc = ['    {0,0,0,0,0,0},']
    for c,mask,x0,y0,y1,advance in glyphs:
        pixels = ((np.array(mask,dtype=np.uint16)*15+127)//255).flatten().tolist()
        if len(pixels)%2: pixels.append(0)
        offset = len(bitmap)
        bitmap.extend((pixels[i]<<4)|pixels[i+1] for i in range(0,len(pixels),2))
        desc.append(f'    {{{offset},{advance},{mask.width},{mask.height},{x0},{-y1}}}, /* U+{ord(c):04X} */')
    first, last = ord(glyphs[0][0]), ord(glyphs[-1][0])
    unicode_list = ','.join(str(ord(g[0])-first) for g in glyphs)
    text = f'''/* Generated by tools/watchface/generate.py from {path.name}, {size}px. */
#include "lvgl.h"
static const uint8_t glyph_bitmap[] = {{
{chunks(bitmap)}
}};
static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{chr(10).join(desc)}
}};
static const uint16_t unicode_list[] = {{{unicode_list}}};
static const lv_font_fmt_txt_cmap_t cmaps[] = {{ {{
    .range_start = {first}, .range_length = {last-first+1}, .glyph_id_start = 1,
    .unicode_list = unicode_list, .glyph_id_ofs_list = NULL,
    .list_length = {len(glyphs)}, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY,
}} }};
static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,
    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 1, .bpp = 4,
    .kern_classes = 0, .bitmap_format = 0,
}};
const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {bottom-top}, .base_line = {bottom},
    .subpx = LV_FONT_SUBPX_NONE, .underline_position = -2, .underline_thickness = 1,
    .dsc = &font_dsc,
}};
'''
    (ASSETS / f'{name}.c').write_text(text,encoding='utf-8')


def stroke(d, points, fill, width):
    pts=[(round(x*S),round(y*S)) for x,y in points]
    w=round(width*S)
    d.line(pts, fill=fill, width=w, joint='curve')
    for x,y in (pts[0],pts[-1]): d.ellipse((x-w/2,y-w/2,x+w/2,y+w/2),fill=fill)


def bezier(p0,p1,p2,p3):
    return [tuple((1-t)**3*p0[j]+3*(1-t)**2*t*p1[j]+3*(1-t)*t*t*p2[j]+t**3*p3[j] for j in (0,1))
            for t in np.linspace(0,1,80)]


def background():
    im=Image.new('RGB',(410*S,502*S));d=ImageDraw.Draw(im)
    for y in range(im.height):
        t=y/(im.height-1)
        d.line((0,y,im.width,y),fill=tuple(round(a+(b-a)*t) for a,b in zip((243,239,250),(248,239,247))))
    # A soft, full-bleed face. The photographed black bezel is not a UI border.
    for flip in [False,True]:
        p=bezier((39,67),(38,37),(64,25),(96,45))
        if flip: p=[(410-x,y) for x,y in p]
        stroke(d,p,'#CEC8E3',7)
    for x0,y0,x1,y1 in [(35,119,44,119),(29,144,52,135)]:
        stroke(d,[(x0,y0),(x1,y1)],'#D1CAE4',7)
        stroke(d,[(410-x0,y0),(410-x1,y1)],'#D1CAE4',7)
    # Sparse faint paper doodles; keep the content area uncluttered.
    for x,y,r in [(23,185,2),(378,201,2),(22,284,2),(375,383,2),(78,367,1.5)]:
        d.ellipse(((x-r)*S,(y-r)*S,(x+r)*S,(y+r)*S),fill='#E9E0F0')
    bolt=[(87,151),(82,160),(89,160),(79,174),(81,164),(75,164)]
    d.polygon([(x*S,y*S) for x,y in bolt],fill='#F0C74D')
    for x in [70,254]:
        d.rounded_rectangle((x*S,452*S,(x+100)*S,486*S),radius=17*S,
                            outline='#B9B8CE',width=round(2*S))
    f=ImageFont.truetype(str(HERE/'fonts/MiSans-Medium.ttf'),21*S)
    d.text((113*S,458*S),'993',font=f,fill='#687299')
    d.text((275*S,458*S),'106',font=f,fill='#687299')
    # Small pink paw, with four separate toe pads.
    for x,y,rx,ry in [(89,475,5.3,4.2),(80,468,2.2,2.7),(86,464,2.1,2.6),(93,464,2.1,2.6),(99,468,2.2,2.7)]:
        d.ellipse(((x-rx)*S,(y-ry)*S,(x+rx)*S,(y+ry)*S),fill='#E5C8CE')
    heart=bezier((330,464),(322,455),(318,467),(330,477))+bezier((330,477),(342,467),(338,455),(330,464))
    d.polygon([(x*S,y*S) for x,y in heart],fill='#DB8BA6')
    fm=ImageFont.truetype(str(HERE/'fonts/ChillRoundF.ttf'),12*S)
    signature='hjc->dy'
    d.text(((410*S-d.textlength(signature,font=fm))/2,463*S),signature,font=fm,fill='#C4BCD4')
    image_c(im.resize((410,502),Image.Resampling.LANCZOS),'face_bg')


def cloud(d, points, fill='#FAF8FF', color='#9BA7C4', width=1.1):
    # Closed cubic outline, in 50x38 icon coordinates.
    paths=[]
    for segment in points: paths.extend(bezier(*segment))
    d.polygon([(x*S,y*S) for x,y in paths],fill=fill)
    stroke(d,paths+[paths[0]],color,width)


def weather_icons():
    shape=[((7,30),(0,29),(0,22),(8,20)),((8,20),(10,12),(22,12),(26,19)),
           ((26,19),(34,17),(41,22),(39,28)),((39,28),(35,33),(15,33),(7,30))]
    for name in ['qing','yun','yin','yu','lei','xue','wu']:
        im=Image.new('RGBA',(50*S,38*S)); d=ImageDraw.Draw(im)
        if name in ['qing','yun']:
            d.ellipse((28*S,3*S,40*S,15*S),fill='#F0C76B')
            for i in range(8):
                a=2*math.pi*i/8
                stroke(d,[(34+8*math.cos(a),9+8*math.sin(a)),(34+10*math.cos(a),9+10*math.sin(a))],'#E3BC6E',.8)
        else:
            back=[tuple((x+8,y-8) for x,y in seg) for seg in shape]
            cloud(d,back,fill='#E5E5F1')
        cloud(d,shape)
        for x in [17,25]: d.ellipse(((x-.8)*S,24*S,(x+.8)*S,25.6*S),fill='#8896B7')
        stroke(d,[(20,28),(22,28)],'#8896B7',.8)
        if name in ['yu','lei']:
            for x in [13,24,34]: stroke(d,[(x,33),(x-1,36)],'#9FB8D8',1)
        if name=='lei': d.polygon([(26*S,28*S),(23*S,33*S),(27*S,33*S),(24*S,38*S),(31*S,31*S),(27*S,31*S)],fill='#EAC45E')
        if name=='xue':
            for x in [13,31]: stroke(d,[(x-2,35),(x+2,35)],'#A8BED7',1);stroke(d,[(x,33),(x,37)],'#A8BED7',1)
        if name=='wu':
            for y in [31,35]: stroke(d,[(9,y),(35,y)],'#ACB6CD',1)
        image_c(im.resize((50,38),Image.Resampling.LANCZOS),'wx_'+name,True)


def layout_header():
    lines=['/* Generated from tools/watchface/layout.json. */','#pragma once']
    for k in ['width','height']: lines.append(f'#define FACE_{k.upper()} {LAYOUT[k]}')
    for k,v in LAYOUT['colors'].items(): lines.append(f'#define FACE_COLOR_{k.upper()} 0x{v}')
    for group in ['time','date','weekday','battery','weather','temperature','animation']:
        for k,v in LAYOUT[group].items(): lines.append(f'#define FACE_{group.upper()}_{k.upper()} {v}')
    lines += ['typedef struct {const char *text; int16_t x,y; uint8_t right,size;} face_phrase_t;',
              'typedef struct {face_phrase_t phrases[8];} face_scene_t;',
              'static const face_scene_t FACE_SCENES[4] = {']
    for scene in LAYOUT['scenes']:
        lines.append('    {{')
        for text,x,y,align,size in scene['phrases']:
            lines.append(f'        {{{json.dumps(text,ensure_ascii=False)},{x},{y},{int(align=="right")},{dict(small=0,normal=1,large=2)[size]}}},')
        lines += ['    }},']
    lines.append('};')
    (ROOT/'components/watch_shell/include/watch_face_layout.h').write_text('\n'.join(lines)+'\n',encoding='utf-8')


def main():
    OUT.mkdir(parents=True,exist_ok=True)
    fonts=HERE/'fonts'; fonts.mkdir(exist_ok=True)
    inputs=ROOT/'.workbuddy/watchface/fonts'
    for name in ['MiSans-Demibold.ttf','MiSans-Medium.ttf','ChillRoundF.ttf','ZCOOLKuaiLe-Regular.ttf']:
        src=inputs/'misans'/name if name.startswith('MiSans') else inputs/name
        if not (fonts/name).exists(): shutil.copy2(src,fonts/name)
    text=''.join(p[0] for s in LAYOUT['scenes'] for p in s['phrases'])+'-^w?τマ'
    font_c(fonts/'MiSans-Demibold.ttf','font_clock',84,'0123456789:-',.915,True)
    font_c(fonts/'MiSans-Medium.ttf','font_meta',19,'0123456789-°星期一二三四五六日')
    for name,size in [('font_phrase',22),('font_phrase_large',32),('font_phrase_small',19)]:
        font_c(fonts/'ZCOOLKuaiLe-Regular.ttf',name,size,text+' ')
    background();weather_icons();layout_header()
    print('Generated 5 bitmap fonts, background, 7 weather icons and the shared layout.')


if __name__=='__main__': main()
